class AssessmentInfo {
  final String title;
  final String status;
  final String examType;
  final String date;
  final String time;
  final String room;
  final int days;
  final int hours;
  final int minutes;
  final int seconds;

  const AssessmentInfo({
    required this.title,
    required this.status,
    required this.examType,
    required this.date,
    required this.time,
    required this.room,
    required this.days,
    required this.hours,
    required this.minutes,
    required this.seconds,
  });
}
